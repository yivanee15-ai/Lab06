module PUYO_GRAV #(parameter W = 6, parameter H = 12)(
    input  [W*H*2-1:0] board,
    input  [W*H-1:0]   mask,
    input  [4*W-1:0]   hgt,
    output [W*H*2-1:0] board_n,
    output [4*W-1:0]   hgt_n
